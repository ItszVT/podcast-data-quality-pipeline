"""Initial PostgreSQL schema, preserving the SQLite persistence contract."""

MIGRATION = (
    1,
    "initial_schema",
    (
        """CREATE TABLE audit_runs (
            audit_run_id TEXT PRIMARY KEY,
            started_at TIMESTAMPTZ NOT NULL,
            completed_at TIMESTAMPTZ,
            input_filename TEXT NOT NULL,
            run_status TEXT NOT NULL CHECK (run_status IN ('running', 'succeeded', 'partial', 'failed')),
            records_processed INTEGER NOT NULL CHECK (records_processed >= 0),
            error_summary TEXT,
            metadata_json JSON NOT NULL DEFAULT '{}'::json
        )""",
        """CREATE TABLE podcast_records (
            record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            audit_run_id TEXT NOT NULL,
            source_row INTEGER NOT NULL CHECK (source_row > 0),
            feed_id TEXT,
            title TEXT,
            website_url TEXT,
            normalized_website_url TEXT,
            record_json JSON NOT NULL,
            UNIQUE (audit_run_id, source_row),
            UNIQUE (audit_run_id, record_id),
            FOREIGN KEY (audit_run_id) REFERENCES audit_runs(audit_run_id) ON DELETE CASCADE
        )""",
        """CREATE TABLE url_checks (
            url_check_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            audit_run_id TEXT NOT NULL,
            record_id BIGINT NOT NULL,
            classification TEXT NOT NULL,
            http_status_code INTEGER,
            original_url TEXT,
            final_url TEXT,
            result_json JSON NOT NULL,
            UNIQUE (audit_run_id, record_id),
            FOREIGN KEY (audit_run_id, record_id)
                REFERENCES podcast_records(audit_run_id, record_id) ON DELETE CASCADE
        )""",
        """CREATE TABLE data_quality_issues (
            issue_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            audit_run_id TEXT NOT NULL,
            record_id BIGINT,
            category TEXT NOT NULL,
            severity TEXT NOT NULL,
            field TEXT,
            message TEXT NOT NULL,
            FOREIGN KEY (audit_run_id) REFERENCES audit_runs(audit_run_id) ON DELETE CASCADE,
            FOREIGN KEY (audit_run_id, record_id)
                REFERENCES podcast_records(audit_run_id, record_id) ON DELETE CASCADE
        )""",
        "CREATE INDEX idx_audit_runs_started_at ON audit_runs(started_at)",
        "CREATE INDEX idx_audit_runs_status ON audit_runs(run_status)",
        "CREATE INDEX idx_podcast_records_feed_id ON podcast_records(feed_id)",
        "CREATE INDEX idx_podcast_records_run ON podcast_records(audit_run_id)",
        "CREATE INDEX idx_url_checks_classification ON url_checks(classification)",
        "CREATE INDEX idx_url_checks_run ON url_checks(audit_run_id)",
        "CREATE INDEX idx_data_quality_issues_category ON data_quality_issues(category)",
        "CREATE INDEX idx_data_quality_issues_run ON data_quality_issues(audit_run_id)",
    ),
)
